using System.Globalization;
using System.Text.Json;

namespace WweAllStars.Launcher.Core;

/// <summary>One value a setting can take: as the game's cvar parses it, and as the player sees it.</summary>
/// <param name="File">
/// A game data file (relative, <c>/</c>-separated) the choice needs: the choice is offered only
/// when the player's disc has it (a language's <c>Coalesced.*</c> file). Null for most choices.
/// </param>
public sealed record SettingChoice(string Value, string Label, string? File = null);

/// <summary>One named set of values for a group row's members, in member order (a Graphics preset).</summary>
public sealed record SchemaPreset(string Value, string Label, IReadOnlyList<string> Values);

/// <summary>
/// One player setting as the game exports it (<c>wweallstars.exe --print-settings-schema</c>,
/// from <c>src/settings/registry.h</c>).
/// </summary>
/// <param name="Type">The cvar's type: <c>bool</c>, <c>int</c>, <c>double</c> or <c>string</c>.</param>
/// <param name="AppliesAtStartup">Takes effect when the game starts, so the launcher shows it.</param>
/// <param name="NativeOnly">Does nothing on the Emulated renderer.</param>
/// <param name="NextStart">The in-game page marks a change as applying at the next start.</param>
/// <param name="RuntimeChoices">
/// Empty when the choices are fixed; <c>gpus</c> when the GPUs the game reports join them, or
/// <c>languages</c> when only the languages on the player's disc stay
/// (<see cref="SettingsSchema.WithRuntimeChoices"/>).
/// </param>
/// <param name="Members">
/// A group row's member keys (the Graphics preset); empty for an ordinary row. A group row names
/// no cvar: its value is derived from its members and never saved on its own.
/// </param>
/// <param name="Presets">A group row's value sets, one value per member; empty for an ordinary row.</param>
/// <param name="Rule">
/// A text row's rule (<see cref="TextRules"/>): it has a typed value up to
/// <paramref name="MaxLength"/> characters instead of choices. Empty for a choice row.
/// </param>
/// <param name="Heading">
/// A sub-heading within the tab (<c>Faster starts</c>), shown above the first of the rows that
/// share it; empty for most rows.
/// </param>
public sealed record SchemaSetting(
    string Key, string Label, string Tab, string Type, string Default,
    bool AppliesAtStartup, bool NativeOnly, bool NextStart,
    IReadOnlyList<SettingChoice> Choices, string Help, string RuntimeChoices = "",
    IReadOnlyList<string>? Members = null, IReadOnlyList<SchemaPreset>? Presets = null,
    string Rule = "", int MaxLength = 0, string Heading = "")
{
    public IReadOnlyList<string> Members { get; init; } = Members ?? [];

    public IReadOnlyList<SchemaPreset> Presets { get; init; } = Presets ?? [];

    public bool IsGroup => Members.Count > 0;

    public bool IsText => Rule.Length > 0;

    /// <summary>The choice a group row shows when no preset matches; shown, never picked.</summary>
    public const string CustomChoice = "custom";
}

/// <summary>
/// The game's player settings list. The launcher builds its Settings screen from the committed
/// copy (<c>SettingsSchema.json</c>, regenerated by <c>scripts/export-settings-schema.ps1</c>),
/// so a setting added in the game needs no second hand-written list here.
/// </summary>
public sealed class SettingsSchema
{
    /// <summary>The export format this launcher reads (2: text rows).</summary>
    public const int Format = 2;

    private SettingsSchema(IReadOnlyList<SchemaSetting> settings) => Settings = settings;

    /// <summary>Every player setting, in the game's order.</summary>
    public IReadOnlyList<SchemaSetting> Settings { get; }

    /// <summary>The settings the launcher shows: those that apply when the game starts.</summary>
    public IReadOnlyList<SchemaSetting> Startup => [.. Settings.Where(s => s.AppliesAtStartup)];

    public SchemaSetting? Find(string key) => Settings.FirstOrDefault(s => s.Key == key);

    /// <summary>Choices filled with the GPUs the game reports (<c>vulkan_device</c>).</summary>
    public const string GpuChoices = "gpus";

    /// <summary>Choices kept only when the game data holds their file (<c>user_language</c>).</summary>
    public const string LanguageChoices = "languages";

    /// <summary>
    /// The schema with the choices that depend on the player's PC and disc filled in: each GPU
    /// in <paramref name="gpus"/> after Automatic, and only the choices whose file exists under
    /// <paramref name="gameDataDirectory"/>. A setting's default always stays (the game falls
    /// back to English when a language is missing).
    /// </summary>
    public SettingsSchema WithRuntimeChoices(string gameDataDirectory, IReadOnlyList<Gpu> gpus) =>
        new([.. Settings.Select(setting => setting with
        {
            Choices =
            [
                .. setting.Choices.Where(c => c.File is null || c.Value == setting.Default ||
                                              System.IO.File.Exists(Path.Combine(gameDataDirectory, c.File))),
                .. setting.RuntimeChoices == GpuChoices
                    ? gpus.Select(g => new SettingChoice(g.Index.ToString(CultureInfo.InvariantCulture), g.Name))
                    : [],
            ],
        })]);

    public static SettingsSchema Parse(string json)
    {
        try
        {
            using var document = JsonDocument.Parse(json);
            var root = document.RootElement;
            var format = root.GetProperty("format").GetInt32();
            if (format != Format)
                throw new LauncherException($"Unsupported settings schema format {format} (expected {Format}).");
            var settings = new List<SchemaSetting>();
            foreach (var item in root.GetProperty("settings").EnumerateArray())
            {
                settings.Add(new SchemaSetting(
                    Text(item, "key"), Text(item, "label"), Text(item, "tab"), Text(item, "type"),
                    Text(item, "default"), item.GetProperty("applies_at_startup").GetBoolean(),
                    item.GetProperty("native_only").GetBoolean(), item.GetProperty("next_start").GetBoolean(),
                    [.. item.GetProperty("choices").EnumerateArray()
                        .Select(c => new SettingChoice(Text(c, "value"), Text(c, "label"), Optional(c, "file")))],
                    Text(item, "help"), Optional(item, "runtime_choices") ?? "",
                    item.TryGetProperty("members", out var members)
                        ? [.. members.EnumerateArray().Select(m => m.GetString() ?? "")]
                        : null,
                    item.TryGetProperty("presets", out var presets)
                        ? [.. presets.EnumerateArray().Select(p => new SchemaPreset(Text(p, "value"), Text(p, "label"),
                            [.. p.GetProperty("values").EnumerateArray().Select(v => v.GetString() ?? "")]))]
                        : null,
                    Optional(item, "kind") == "text" ? Text(item, "rule") : "",
                    item.TryGetProperty("max_length", out var maxLength) ? maxLength.GetInt32() : 0,
                    Optional(item, "heading") ?? ""));
            }
            return new SettingsSchema(settings);
        }
        catch (Exception error) when (error is JsonException or KeyNotFoundException or InvalidOperationException)
        {
            throw new LauncherException($"The settings schema does not parse: {error.Message}", error);
        }
    }

    /// <summary>The committed copy of the game's export, built into the launcher.</summary>
    public static SettingsSchema Committed() => Parse(CommittedJson());

    /// <summary>The committed copy's text, as the game exported it.</summary>
    public static string CommittedJson()
    {
        using var stream = typeof(SettingsSchema).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new LauncherException("The launcher was built without its settings schema.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    /// <summary>The embedded resource holding the committed schema.</summary>
    public const string ResourceName = "SettingsSchema.json";

    private static string Text(JsonElement item, string name) => item.GetProperty(name).GetString() ?? "";

    private static string? Optional(JsonElement item, string name) =>
        item.TryGetProperty(name, out var value) ? value.GetString() : null;
}
