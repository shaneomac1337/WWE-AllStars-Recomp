using WweAllStars.Launcher.Core;

namespace WweAllStars.Launcher.Tests;

/// <summary>Config mods (spec, "Coalesced bundle", "Overlay folder"): a mod's <c>config/</c> merged into TU2's bundles.</summary>
public sealed class ModConfigTests : IDisposable
{
    private readonly string _root = Directory.CreateTempSubdirectory("wwe-mods-config-").FullName;
    private readonly PortableLayout _layout;

    public ModConfigTests() => _layout = new PortableLayout(_root);

    public void Dispose() => Directory.Delete(_root, recursive: true);

    private ModLibrary Library() => new(_layout, new KnownGameFiles(["Engine.xxx"]), new FakeLinker(), new FakeRecycleBin());

    private const string EngineIni = @"..\Game\Config\Xenon\Cooked\Xe-Engine.ini";
    private const string GameIni = @"..\Game\Config\Xenon\Cooked\Xe-Game.ini";
    private const string NamesInt = @"..\Game\Localization\INT\CharacterNames.int";
    private const string NamesDeu = @"..\Game\Localization\DEU\CharacterNames.deu";

    private const string Tu2Engine = "[URL]\r\nProtocol=unreal\r\n";
    private const string Tu2Game =
        "[Engine.GameInfo]\r\n" +
        "DefaultGame=Game.DerivedGameInfo\r\n" +
        "MaxPlayers=4\r\n" +
        "\r\n" +
        "[Game.Tuning]\r\n" +
        "AttackDelay=1.0\r\n" +
        "Paths=A\r\n" +
        "Paths=B\r\n";
    private const string Tu2NamesInt = "﻿; autogenerated\n[Names]\nCHR_101=Hulk Hogan\nCHR_102=John Cena\n";
    private const string Tu2NamesDeu = "﻿; autogenerated\n[Names]\nCHR_101=Hulk Hogan\n";

    private string Tu2()
    {
        var folder = _layout.UpdateDataDirectory;
        Directory.CreateDirectory(folder);
        File.WriteAllBytes(Path.Combine(folder, "Coalesced.ini"), CoalescedBundleTests.Bundle((EngineIni, Tu2Engine), (GameIni, Tu2Game)));
        File.WriteAllBytes(Path.Combine(folder, "Coalesced.int"), CoalescedBundleTests.Bundle((NamesInt, Tu2NamesInt)));
        File.WriteAllBytes(Path.Combine(folder, "Coalesced.deu"), CoalescedBundleTests.Bundle((NamesDeu, Tu2NamesDeu)));
        File.WriteAllText(Path.Combine(folder, "Engine.xxx"), "tu2 engine");
        File.WriteAllText(Path.Combine(folder, "PatchTOC.txt"),
            "999 0 0 .\\Coalesced.ini 0 \r\n888 0 0 .\\Coalesced.int 0 \r\n777 0 0 .\\Coalesced.deu 0 \r\n1409024 6464092 0 .\\Engine.xxx 0 \r\n");
        return folder;
    }

    /// <summary>A mod with <c>config/</c> files, by their path under <c>config/</c>.</summary>
    private void Mod(string folder, params (string Path, string Text)[] config)
    {
        var path = Path.Combine(_layout.ModsDirectory, folder);
        Directory.CreateDirectory(path);
        File.WriteAllText(Path.Combine(path, ModLibrary.ManifestFileName),
            $"name = \"{folder}\"\nversion = \"1.0\"\ngame = \"TU2\"\nkind = \"gameplay\"\n");
        foreach (var (file, text) in config)
        {
            var target = Path.Combine(path, "config", file);
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.WriteAllText(target, text);
        }
    }

    private PreparedMods Play(params string[] on)
    {
        var tu2 = Tu2();
        var library = Library();
        library.List();
        foreach (var id in on) library.SetEnabled(id, true);
        return library.PrepareForPlay(tu2, online: false);
    }

    private static string Body(PreparedMods prepared, string bundle, string ini) =>
        CoalescedBundle.Parse(File.ReadAllBytes(Path.Combine(prepared.UpdateDataRoot, bundle))).Find(ini)!.Body;

    private string GameIniAfter(params string[] edits)
    {
        Mod("Tuning", ("Xe-Game.ini", string.Join("\r\n", edits) + "\r\n"));
        return Body(Play("Tuning"), "Coalesced.ini", "Xe-Game.ini");
    }

    [Fact]
    public void Key_equals_sets_an_existing_key_in_place()
    {
        var body = GameIniAfter("[Game.Tuning]", "AttackDelay=0.5");

        Assert.Equal(Tu2Game.Replace("AttackDelay=1.0", "AttackDelay=0.5", StringComparison.Ordinal), body);
    }

    [Fact]
    public void Key_equals_on_a_key_with_several_values_leaves_one()
    {
        var body = GameIniAfter("[game.tuning]", "paths=C");

        Assert.EndsWith("AttackDelay=1.0\r\npaths=C\r\n", body);
    }

    [Fact]
    public void Key_equals_adds_a_missing_key_at_the_end_of_its_section()
    {
        var body = GameIniAfter("[Engine.GameInfo]", "bPauseable=False");

        Assert.Contains("MaxPlayers=4\r\nbPauseable=False\r\n\r\n[Game.Tuning]", body);
    }

    [Fact]
    public void An_edit_to_a_missing_section_adds_the_section()
    {
        var body = GameIniAfter("[Game.New]", "Speed=2");

        Assert.Equal(Tu2Game + "\r\n[Game.New]\r\nSpeed=2\r\n", body);
    }

    [Fact]
    public void Plus_key_adds_a_value_only_once()
    {
        var body = GameIniAfter("[Game.Tuning]", "+Paths=B", "+Paths=C", "+Paths=C");

        Assert.EndsWith("Paths=A\r\nPaths=B\r\nPaths=C\r\n", body);
    }

    [Fact]
    public void Minus_key_removes_that_value()
    {
        var body = GameIniAfter("[Game.Tuning]", "-Paths=A");

        Assert.EndsWith("AttackDelay=1.0\r\nPaths=B\r\n", body);
    }

    [Fact]
    public void Dot_key_adds_a_duplicate_value()
    {
        var body = GameIniAfter("[Game.Tuning]", ".Paths=B");

        Assert.EndsWith("Paths=A\r\nPaths=B\r\nPaths=B\r\n", body);
    }

    [Fact]
    public void Comments_and_lines_outside_a_section_are_not_edits()
    {
        var body = GameIniAfter("; my tuning", "AttackDelay=9", "[Game.Tuning]", "; AttackDelay=8");

        Assert.Equal(Tu2Game, body);
    }

    [Fact]
    public void Edits_apply_in_load_order_and_the_later_mod_wins()
    {
        Mod("Slow", ("Xe-Game.ini", "[Game.Tuning]\r\nAttackDelay=2.0\r\n+Paths=Slow\r\n"));
        Mod("Fast", ("Xe-Game.ini", "[Game.Tuning]\r\nAttackDelay=0.5\r\n"));
        File.WriteAllLines(Path.Combine(_layout.ModsDirectory, ModLibrary.LoadOrderFileName), ["on | Slow", "on | Fast"]);

        var prepared = Play();

        Assert.EndsWith("AttackDelay=0.5\r\nPaths=A\r\nPaths=B\r\nPaths=Slow\r\n", Body(prepared, "Coalesced.ini", "Xe-Game.ini"));
        Assert.Empty(prepared.Report.ConfigConflicts);
    }

    [Fact]
    public void The_rebuilt_bundle_gets_its_new_size_in_PatchTOC_and_the_others_are_TU2s()
    {
        Mod("Tuning", ("Xe-Game.ini", "[Game.Tuning]\r\nAttackDelay=0.25\r\n"));

        var prepared = Play("Tuning");

        var size = new FileInfo(Path.Combine(prepared.UpdateDataRoot, "Coalesced.ini")).Length;
        var toc = File.ReadAllText(Path.Combine(prepared.UpdateDataRoot, "PatchTOC.txt")).Split("\r\n", StringSplitOptions.RemoveEmptyEntries);
        Assert.Equal($"{size} 0 0 .\\Coalesced.ini 0 ", toc[0]);
        Assert.Equal("888 0 0 .\\Coalesced.int 0 ", toc[1]);
        Assert.Equal(Tu2Engine, Body(prepared, "Coalesced.ini", "Xe-Engine.ini"));
        Assert.Equal(File.ReadAllBytes(Path.Combine(_layout.UpdateDataDirectory, "Coalesced.int")),
            File.ReadAllBytes(Path.Combine(prepared.UpdateDataRoot, "Coalesced.int")));
        Assert.Equal(CoalescedBundleTests.Bundle((EngineIni, Tu2Engine), (GameIni, Tu2Game)),
            File.ReadAllBytes(Path.Combine(_layout.UpdateDataDirectory, "Coalesced.ini")));
    }

    private const string WholeGame =
        "[Engine.GameInfo]\r\nDefaultGame=Game.MyGameInfo\r\nMaxPlayers=8\r\n\r\n[Game.Tuning]\r\nAttackDelay=3.0\r\nPaths=X\r\nPaths=Y\r\n";

    [Fact]
    public void A_file_without_every_key_of_the_inner_ini_is_edits_not_a_replacement()
    {
        Mod("Partial", ("Xe-Game.ini", "[Engine.GameInfo]\r\nDefaultGame=Game.MyGameInfo\r\n[Game.Tuning]\r\nAttackDelay=3.0\r\nPaths=X\r\n"));

        var prepared = Play("Partial");

        Assert.Equal(
            "[Engine.GameInfo]\r\nDefaultGame=Game.MyGameInfo\r\nMaxPlayers=4\r\n\r\n[Game.Tuning]\r\nAttackDelay=3.0\r\nPaths=X\r\n",
            Body(prepared, "Coalesced.ini", "Xe-Game.ini"));
    }

    [Fact]
    public void An_inner_ini_shipped_complete_replaces_TU2s()
    {
        Mod("Rewrite", ("Xe-Game.ini", WholeGame));

        var prepared = Play("Rewrite");

        Assert.Equal(WholeGame, Body(prepared, "Coalesced.ini", "Xe-Game.ini"));
    }

    [Fact]
    public void Two_mods_replacing_the_same_inner_ini_conflict_and_the_later_one_wins()
    {
        Mod("Rewrite A", ("Xe-Game.ini", WholeGame));
        Mod("Rewrite B", ("Xe-Game.ini", WholeGame.Replace("3.0", "4.0", StringComparison.Ordinal)));
        Mod("Tweak", ("Xe-Game.ini", "[Game.Tuning]\r\n+Paths=Z\r\n"));

        var prepared = Play("Rewrite A", "Rewrite B", "Tweak");

        Assert.Equal(WholeGame.Replace("3.0", "4.0", StringComparison.Ordinal) + "Paths=Z\r\n",
            Body(prepared, "Coalesced.ini", "Xe-Game.ini"));
        var conflict = Assert.Single(prepared.Report.ConfigConflicts);
        Assert.Equal("Coalesced.ini", conflict.Bundle);
        Assert.Equal("Xe-Game.ini", conflict.Ini);
        Assert.Equal(["Rewrite A", "Rewrite B"], conflict.Mods);
        Assert.Equal("Rewrite B", conflict.Winner);
        Assert.Contains("config conflict: Coalesced.ini Xe-Game.ini is replaced whole by Rewrite A, Rewrite B; Rewrite B wins",
            prepared.Report.Lines());
    }

    [Fact]
    public void A_localised_edit_goes_to_that_languages_bundle_only()
    {
        Mod("Names", ("int/CharacterNames.int", "[Names]\nCHR_101=Hollywood Hogan\n"));

        var prepared = Play("Names");

        Assert.Equal(Tu2NamesInt.Replace("Hulk Hogan", "Hollywood Hogan", StringComparison.Ordinal),
            Body(prepared, "Coalesced.int", "CharacterNames.int"));
        Assert.Equal(Tu2NamesDeu, Body(prepared, "Coalesced.deu", "CharacterNames.deu"));
        Assert.Equal(Tu2Game, Body(prepared, "Coalesced.ini", "Xe-Game.ini"));
    }

    [Fact]
    public void An_edit_for_a_language_TU2_does_not_ship_is_a_problem()
    {
        Mod("Japanese", ("jpn/CharacterNames.jpn", "[Names]\nCHR_101=X\n"));

        var mod = Assert.Single(Library().List());

        Assert.Equal(["config/jpn/ edits Coalesced.jpn, which Title Update 2 doesn't ship."], mod.Problems);
    }

    [Fact]
    public void A_mod_lists_its_config_files()
    {
        Mod("Both", ("Xe-Game.ini", "[A]\nB=1\n"), ("deu/CharacterNames.deu", "[Names]\nCHR_101=X\n"));

        var mod = Assert.Single(Library().List());

        Assert.Empty(mod.Problems);
        Assert.Equal([("Coalesced.deu", "CharacterNames.deu"), ("Coalesced.ini", "Xe-Game.ini")],
            mod.Config.Select(file => (file.Bundle, file.Ini)).Order());
    }

    [Fact]
    public void The_load_report_lists_the_config_edits_applied()
    {
        Mod("Tuning", ("Xe-Game.ini", "[Game.Tuning]\r\nAttackDelay=0.5\r\n+Paths=C\r\n"), ("Xe-Missing.ini", "[A]\r\nB=1\r\n"));

        var report = Play("Tuning").Report;

        Assert.Equal(
        [
            "mods: 1 in use",
            "mod 1: Tuning 1.0 (Tuning): config/Xe-Game.ini",
            "config: Tuning: Coalesced.ini Xe-Game.ini: 2 edits",
            "config: Tuning: Coalesced.ini Xe-Missing.ini: left out, the bundle has no such ini",
        ], report.Lines());
    }

    [Fact]
    public void Changing_a_config_file_rebuilds_the_update_folder()
    {
        Mod("Tuning", ("Xe-Game.ini", "[Game.Tuning]\r\nAttackDelay=0.5\r\n"));
        var prepared = Play("Tuning");
        File.WriteAllText(Path.Combine(_layout.ModsDirectory, "Tuning", "config", "Xe-Game.ini"), "[Game.Tuning]\r\nAttackDelay=0.75\r\n");
        File.SetLastWriteTimeUtc(Path.Combine(_layout.ModsDirectory, "Tuning", "config", "Xe-Game.ini"), DateTime.UtcNow.AddMinutes(1));

        prepared = Library().PrepareForPlay(_layout.UpdateDataDirectory, online: false);

        Assert.Contains("AttackDelay=0.75\r\n", Body(prepared, "Coalesced.ini", "Xe-Game.ini"));
    }
}
